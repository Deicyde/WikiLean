#!/usr/bin/env python3
"""Keep .github/backup-wrangler/ the exact Wrangler subset of wiki/package-lock.json.

The Backup D1 workflow needs only Wrangler. Installing the whole wiki tree with
``npm ci --prefix wiki`` ran every dependency's install scripts (Vitest, Playwright,
esbuild, ...) on the runner one step before CLOUDFLARE_API_TOKEN is handed to
Wrangler. ``.github/backup-wrangler`` instead declares Wrangler alone, and its
lockfile is the dependency closure of ``node_modules/wrangler`` copied from
``wiki/package-lock.json``: the same install paths, versions, resolved URLs and
integrity hashes the Worker toolchain already pins. Nothing is resolved afresh.

    python3 scripts/backup_wrangler_lock.py --check   # CI: fail on any drift
    python3 scripts/backup_wrangler_lock.py --write   # regenerate after a Wrangler bump

``--check`` fails when the wiki lockfile moves Wrangler or any package in its
closure, so the backup job can never silently run a different Wrangler than the
one the repository reviewed.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WIKI_LOCK = ROOT / "wiki" / "package-lock.json"
TARGET = ROOT / ".github" / "backup-wrangler"
NAME = "wikilean-ci-backup-wrangler"
PINNED_FIELDS = ("version", "resolved", "integrity")


def _resolve(packages: dict, from_path: str, name: str) -> str | None:
    """Node's lookup of ``name`` from the package installed at ``from_path``."""
    base = from_path
    while True:
        candidate = f"{base}/node_modules/{name}" if base else f"node_modules/{name}"
        if candidate in packages:
            return candidate
        if not base:
            return None
        cut = base.rfind("/node_modules/")
        base = base[:cut] if cut >= 0 else ""


def closure(packages: dict, start: str = "node_modules/wrangler") -> tuple[list[str], set[str]]:
    """Install paths reachable from ``start`` and the subset reachable without optional edges."""
    if start not in packages:
        raise SystemExit(f"{WIKI_LOCK}: no {start} entry")
    seen: dict[str, bool] = {}  # path -> reachable through required edges only
    stack: list[tuple[str, bool]] = [(start, True)]
    while stack:
        path, required = stack.pop()
        if path in seen and (seen[path] or not required):
            continue
        seen[path] = seen.get(path, False) or required
        entry = packages[path]
        peers_meta = entry.get("peerDependenciesMeta") or {}
        edges = [(name, True) for name in entry.get("dependencies") or {}]
        edges += [(name, False) for name in entry.get("optionalDependencies") or {}]
        edges += [(name, not (peers_meta.get(name) or {}).get("optional", False))
                  for name in entry.get("peerDependencies") or {}
                  if not (peers_meta.get(name) or {}).get("optional", False)]
        for name, edge_required in edges:
            target = _resolve(packages, path, name)
            if target is None:
                if edge_required:
                    raise SystemExit(f"{WIKI_LOCK}: {path} needs {name}, which is not in the lockfile")
                continue  # an optional dependency for another platform
            stack.append((target, required and edge_required))
    return sorted(seen), {path for path, req in seen.items() if req}


def build(wiki_lock: dict) -> tuple[dict, dict]:
    packages = wiki_lock["packages"]
    paths, required = closure(packages)
    version = packages["node_modules/wrangler"]["version"]
    manifest = {
        "name": NAME,
        "private": True,
        "version": "0.0.0",
        "description": "Wrangler alone for .github/workflows/backup-d1.yml; generated by scripts/backup_wrangler_lock.py",
        "devDependencies": {"wrangler": version},
    }
    out: dict[str, dict] = {"": {"name": NAME, "version": "0.0.0", "devDependencies": {"wrangler": version}}}
    for path in paths:
        # Every package here hangs off a devDependency, so it is "dev"; it is also
        # "optional" when only optional edges reach it. Keep the wiki entry's key
        # order (npm's), editing the flags in place, so npm leaves the file as is.
        source = packages[path]
        flags = {"dev": True, "optional": path not in required, "devOptional": False}
        entry: dict = {}
        for key, value in source.items():
            if key in flags:
                if flags[key]:
                    entry[key] = True
            else:
                entry[key] = value
        # A flag the wiki entry lacked (a package the Worker also needs at runtime
        # is not "dev" there) goes at the end; npm would reorder it harmlessly.
        entry.update({key: True for key, on in flags.items() if on and key not in entry})
        out[path] = entry
    lock = {"name": NAME, "version": "0.0.0", "lockfileVersion": 3, "requires": True, "packages": out}
    return manifest, lock


def render(value: dict) -> str:
    return json.dumps(value, indent=2, ensure_ascii=False) + "\n"


def problems(wiki_lock: dict, manifest: dict, lock: dict) -> list[str]:
    want_manifest, want_lock = build(wiki_lock)
    found: list[str] = []
    if manifest != want_manifest:
        found.append("package.json differs from the generated manifest (Wrangler version or name)")
    have, want = lock.get("packages", {}), want_lock["packages"]
    for path in sorted(set(have) | set(want)):
        if path not in want:
            found.append(f"{path}: not in Wrangler's closure in wiki/package-lock.json")
        elif path not in have:
            found.append(f"{path}: missing (Wrangler's closure in wiki/package-lock.json has it)")
        elif path and any(have[path].get(f) != want[path].get(f) for f in PINNED_FIELDS):
            found.append(f"{path}: version/resolved/integrity differ from wiki/package-lock.json")
    if have.get("") != want.get(""):
        found.append("root entry differs from the generated one")
    return found


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    args = parser.parse_args(argv)
    wiki_lock = json.loads(WIKI_LOCK.read_text(encoding="utf-8"))
    if args.write:
        manifest, lock = build(wiki_lock)
        TARGET.mkdir(parents=True, exist_ok=True)
        (TARGET / "package.json").write_text(render(manifest), encoding="utf-8")
        (TARGET / "package-lock.json").write_text(render(lock), encoding="utf-8")
        print(f"wrote {TARGET.relative_to(ROOT)} for wrangler {manifest['devDependencies']['wrangler']}: "
              f"{len(lock['packages']) - 1} packages")
        return 0
    manifest = json.loads((TARGET / "package.json").read_text(encoding="utf-8"))
    lock = json.loads((TARGET / "package-lock.json").read_text(encoding="utf-8"))
    found = problems(wiki_lock, manifest, lock)
    for problem in found:
        print(f".github/backup-wrangler: {problem}", file=sys.stderr)
    if found:
        print("regenerate with: python3 scripts/backup_wrangler_lock.py --write", file=sys.stderr)
        return 1
    print(f".github/backup-wrangler pins wrangler {manifest['devDependencies']['wrangler']} "
          f"({len(lock['packages']) - 1} packages) exactly as wiki/package-lock.json does.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

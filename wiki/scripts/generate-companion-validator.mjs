// Reproducible offline build from the exact upstream schema, never a second schema.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { build } from 'esbuild';

const dir = new URL('../src/vendor/fca/', import.meta.url);
const bytes = readFileSync(new URL('companion.schema.json', dir));
const provenance = JSON.parse(readFileSync(new URL('provenance.json', dir), 'utf8'));
if (createHash('sha256').update(bytes).digest('hex') !== provenance.sha256) {
  throw new Error('Bundled FCA schema differs from its pinned upstream digest');
}
const ajv = new Ajv2020({ strict: false, allErrors: true, code: { source: true }, validateFormats: false });
const validate = ajv.compile(JSON.parse(bytes));
const generated = await build({
  stdin: { contents: standaloneCode(ajv, validate), resolveDir: fileURLToPath(new URL('../', import.meta.url)) },
  bundle: true, format: 'esm', platform: 'browser', write: false, minify: true,
});
const output = '// GENERATED by scripts/generate-companion-validator.mjs; do not edit.\n'
  + `// Upstream ${provenance.commit}; schema sha256 ${provenance.sha256}.\n`
  + generated.outputFiles[0].text;
const target = new URL('validate.js', dir);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('Generated FCA validator is stale');
} else writeFileSync(target, output);
